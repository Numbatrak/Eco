-- follow_ups table (org-scoped) + remove permissive abandoned_carts policies

-- ---------------------------------------------------------------------------
-- follow_ups
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.follow_ups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id uuid REFERENCES public.organizations(id) ON DELETE CASCADE,
  order_id uuid REFERENCES public.orders(id) ON DELETE SET NULL,
  abandoned_cart_id uuid REFERENCES public.abandoned_carts(id) ON DELETE SET NULL,
  assigned_to uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'pending',
  priority text NOT NULL DEFAULT 'medium',
  started_at timestamptz,
  first_contact_at timestamptz,
  completed_at timestamptz,
  response_time_minutes integer,
  resolution_time_minutes integer,
  outcome text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT follow_ups_status_check CHECK (
    status = ANY (ARRAY['pending'::text, 'in_progress'::text, 'completed'::text, 'cancelled'::text])
  ),
  CONSTRAINT follow_ups_priority_check CHECK (
    priority = ANY (ARRAY['low'::text, 'medium'::text, 'high'::text, 'urgent'::text])
  ),
  CONSTRAINT follow_ups_outcome_check CHECK (
    outcome IS NULL OR outcome = ANY (
      ARRAY['converted'::text, 'not_interested'::text, 'follow_up_needed'::text, 'resolved'::text, 'other'::text]
    )
  )
);

ALTER TABLE public.follow_ups ADD COLUMN IF NOT EXISTS organization_id uuid REFERENCES public.organizations(id) ON DELETE CASCADE;

UPDATE public.follow_ups fu
SET organization_id = o.organization_id
FROM public.orders o
WHERE fu.order_id = o.id AND fu.organization_id IS NULL;

UPDATE public.follow_ups fu
SET organization_id = ac.organization_id
FROM public.abandoned_carts ac
WHERE fu.abandoned_cart_id = ac.id AND fu.organization_id IS NULL;

CREATE INDEX IF NOT EXISTS idx_follow_ups_organization_id ON public.follow_ups (organization_id);
CREATE INDEX IF NOT EXISTS idx_follow_ups_assigned_to ON public.follow_ups (assigned_to);
CREATE INDEX IF NOT EXISTS idx_follow_ups_status ON public.follow_ups (status);
CREATE INDEX IF NOT EXISTS idx_follow_ups_created_at ON public.follow_ups (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_follow_ups_order_id ON public.follow_ups (order_id);
CREATE INDEX IF NOT EXISTS idx_follow_ups_abandoned_cart_id ON public.follow_ups (abandoned_cart_id);

CREATE OR REPLACE FUNCTION public.set_follow_up_organization_id()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.organization_id IS NOT NULL THEN
    RETURN NEW;
  END IF;
  IF NEW.order_id IS NOT NULL THEN
    SELECT organization_id INTO NEW.organization_id FROM public.orders WHERE id = NEW.order_id;
  ELSIF NEW.abandoned_cart_id IS NOT NULL THEN
    SELECT organization_id INTO NEW.organization_id FROM public.abandoned_carts WHERE id = NEW.abandoned_cart_id;
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_trigger t
    INNER JOIN pg_class c ON c.oid = t.tgrelid
    INNER JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relname = 'follow_ups'
      AND t.tgname = 'follow_ups_set_organization_id'
      AND NOT t.tgisinternal
  ) THEN
    CREATE TRIGGER follow_ups_set_organization_id
      BEFORE INSERT OR UPDATE ON public.follow_ups
      FOR EACH ROW
      EXECUTE FUNCTION public.set_follow_up_organization_id();
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_trigger t
    INNER JOIN pg_class c ON c.oid = t.tgrelid
    INNER JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relname = 'follow_ups'
      AND t.tgname = 'update_follow_ups_updated_at'
      AND NOT t.tgisinternal
  ) THEN
    CREATE TRIGGER update_follow_ups_updated_at
      BEFORE UPDATE ON public.follow_ups
      FOR EACH ROW
      EXECUTE FUNCTION public.update_updated_at_column();
  END IF;
END $$;

ALTER TABLE public.follow_ups ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'follow_ups' AND policyname = 'follow_ups_select'
  ) THEN
    CREATE POLICY "follow_ups_select" ON public.follow_ups
      FOR SELECT TO authenticated
      USING (
        organization_id IN (
          SELECT organization_id FROM public.organization_members WHERE user_id = auth.uid()
        )
      );
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'follow_ups' AND policyname = 'follow_ups_insert'
  ) THEN
    CREATE POLICY "follow_ups_insert" ON public.follow_ups
      FOR INSERT TO authenticated
      WITH CHECK (
        organization_id IN (
          SELECT organization_id FROM public.organization_members WHERE user_id = auth.uid()
        )
      );
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'follow_ups' AND policyname = 'follow_ups_update'
  ) THEN
    CREATE POLICY "follow_ups_update" ON public.follow_ups
      FOR UPDATE TO authenticated
      USING (
        organization_id IN (
          SELECT organization_id FROM public.organization_members WHERE user_id = auth.uid()
        )
        AND (
          assigned_to = auth.uid()
          OR public.has_any_org_role(organization_id, ARRAY['Owner', 'Admin', 'Manager'])
        )
      );
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'follow_ups' AND policyname = 'follow_ups_delete'
  ) THEN
    CREATE POLICY "follow_ups_delete" ON public.follow_ups
      FOR DELETE TO authenticated
      USING (
        public.has_any_org_role(organization_id, ARRAY['Owner', 'Admin'])
        OR assigned_to = auth.uid()
      );
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- abandoned_carts: drop overly permissive policies (cross-tenant risk)
-- ---------------------------------------------------------------------------
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'abandoned_carts'
      AND policyname = 'Authenticated users can view abandoned carts'
  ) THEN
    DROP POLICY "Authenticated users can view abandoned carts" ON public.abandoned_carts;
  END IF;
  IF EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'abandoned_carts'
      AND policyname = 'Authenticated users can update abandoned carts'
  ) THEN
    DROP POLICY "Authenticated users can update abandoned carts" ON public.abandoned_carts;
  END IF;
  IF EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'abandoned_carts'
      AND policyname = 'Authenticated users can delete abandoned carts'
  ) THEN
    DROP POLICY "Authenticated users can delete abandoned carts" ON public.abandoned_carts;
  END IF;
END $$;
